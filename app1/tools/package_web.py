#!/usr/bin/env python3
"""Bundle web/ into one HTML file for delivery through a GitHub raw link.

python3 app1/tools/package_web.py [--check] [web directory]
No firmware or build tools are needed; export_web.py calls this after generating the manifest.
"""
import argparse
import base64
import json
from pathlib import Path
import re

WEB = Path(__file__).resolve().parents[2] / 'web'


def render(web):
    web = Path(web)
    html = (web / 'index.html').read_text()

    def stylesheet(match):
        path = web / match[1]
        css = path.read_text()

        def asset(url):
            path_to_asset = path.parent / url[1]
            encoded = base64.b64encode(path_to_asset.read_bytes()).decode('ascii')
            if path_to_asset.suffix != '.woff2':
                raise ValueError(f'unsupported CSS asset: {path_to_asset}')
            return f'url(data:font/woff2;base64,{encoded})'

        css = re.sub(r'url\(\./([^)]*)\)', asset, css)
        if '</style' in css.lower():
            raise ValueError('stylesheet contains a closing style tag')
        return '<style>\n' + css + '\n</style>'

    html = re.sub(r'<link rel="stylesheet" href="([^"]+)">', stylesheet, html)
    manifest = json.dumps(json.loads((web / 'patches.json').read_text()), separators=(',', ':'))
    manifest = manifest.replace('<', r'\u003c')
    core = base64.b64encode((web / 'patcher.js').read_bytes()).decode('ascii')
    imports = json.dumps({'imports': {'./patcher.js': 'data:text/javascript;base64,' + core}})
    app = (web / 'app.js').read_text()
    if '</script' in app.lower():
        raise ValueError('app.js contains a closing script tag')
    scripts = ('<script id="patch-manifest" type="application/json">' + manifest + '</script>\n'
               '<script type="importmap">' + imports + '</script>\n'
               '<script type="module">\n' + app + '\n</script>')
    marker = '<script type="module" src="app.js"></script>'
    if html.count(marker) != 1:
        raise ValueError('expected one app.js module entry point')
    html = html.replace(marker, scripts)
    html = html.replace('<html lang="en">', '<html lang="en" data-jam-tricks-standalone="1">')
    return '<!-- Generated by app1/tools/package_web.py; edit web/ sources instead. -->\n' + html


def build(web=WEB, check=False):
    path = Path(web) / 'standalone.html'
    html = render(web)
    if check:
        if not path.exists() or path.read_text() != html:
            raise SystemExit('web/standalone.html is stale; run python3 app1/tools/package_web.py')
    else:
        path.write_text(html)
    print(f'{"checked" if check else "wrote"} {path} ({len(html.encode())} bytes)')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('web', nargs='?', type=Path, default=WEB)
    args = parser.parse_args()
    build(args.web, args.check)
