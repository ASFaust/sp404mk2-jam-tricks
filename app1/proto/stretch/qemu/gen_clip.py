"""Write clip.h for bench.c: 3 s of the "mix" corpus clip, stereo int16.
    python gen_clip.py        (from app1/proto/stretch/qemu)"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
import corpus  # noqa: E402

x = corpus.load_corpus(["mix"])["mix"][:3 * corpus.SR]
with open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "clip.h"), "w") as f:
    f.write('/* generated by gen_clip.py: 3 s of the "mix" corpus clip, stereo int16 */\n')
    f.write(f"#define CLIP_LEN {len(x)}\nstatic const int16_t clip[] = {{\n")
    flat = x.reshape(-1)
    for i in range(0, len(flat), 16):
        f.write(",".join(str(int(v)) for v in flat[i:i + 16]) + ",\n")
    f.write("};\n")
print("clip.h:", len(x), "frames")
